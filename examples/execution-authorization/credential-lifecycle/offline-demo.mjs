/** Generates one fixed synthetic run and separate reproduction trust/scope files. No real credentials. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { requestDigest } from '../gate.mjs';
import { createFixture, credentialOperation } from './fixtures.mjs';
import { createCredentialEvidence, verifyCredentialEvidence, EXPECTATION_FORMAT } from './offline.mjs';

export function createOfflineDemo() {
  const fixture = createFixture(), parent = credentialOperation();
  const expectedDigests = [], reports = [];
  const execute = (operation, options) => {
    const input = fixture.input(operation, options);
    expectedDigests.push(requestDigest(input.request.payload));
    const step = fixture.execute(input);
    if (step.result.execution !== 'COMPLETED') throw new Error('SYNTHETIC_SCENARIO_FAILED');
    reports.push(step.result);
  };
  execute(parent);
  execute({ ...parent, kind: 'read' });
  const credential = fixture.providerOwned.control.takeDelivered(parent.credentialRef);
  // Two distinct signed requests for the same operation must remain distinct.
  execute({ ...parent, kind: 'use' }, { credential });
  execute({ ...parent, kind: 'use' }, { credential });
  execute({ ...parent, kind: 'revoke' });
  const trust = fixture.exportTrust();
  const evidence = createCredentialEvidence({ contextId: trust.contextId, reports,
    providerAudit: fixture.providerOwned.provider.observe() });
  const expectation = { format: EXPECTATION_FORMAT, contextId: trust.contextId, requestDigests: expectedDigests };
  const verification = verifyCredentialEvidence({ evidence, trust, expectedContextId: expectation.contextId,
    expectedRequestDigests: expectation.requestDigests });
  if (verification.evidence_consistency !== 'VALID' || verification.overall_status !== 'INDETERMINATE')
    throw new Error('OFFLINE_SCENARIO_FAILED');
  const summary = { format: 'evidect-credential-offline-demo/1', test_result: 'PASS',
    scenario: 'mint-read-use-use-revoke', signed_request_count: expectedDigests.length,
    provider_request_count: evidence.provider_observation.records.length,
    evidence_consistency: verification.evidence_consistency, overall_status: verification.overall_status,
    report_signed: false, production_observed: false, independent_assessment: false,
    provider_log_completeness: 'NOT_ESTABLISHED', historical_authorization: 'NOT_ASSESSED',
    notice: 'Synthetic reproduction trust and scope are generated by the same controller. Receiver adoption is a separate decision.' };
  return { evidence, trust, expectation, summary };
}

export function writeOfflineDemo(outputDirectory) {
  if (typeof outputDirectory !== 'string' || outputDirectory.length === 0 || outputDirectory.includes('\0'))
    throw new Error('OUTPUT_DIRECTORY_REQUIRED');
  const generated = createOfflineDemo();
  const directory = resolve(outputDirectory);
  // Exclusive directory creation prevents replacement of any existing output.
  mkdirSync(directory, { mode: 0o700 });
  const files = {};
  for (const [name, value] of [['evidence.json', generated.evidence], ['trust.json', generated.trust],
    ['expectation.json', generated.expectation], ['demo-summary.json', generated.summary]]) {
    const bytes = Buffer.from(JSON.stringify(value, null, 2) + '\n');
    writeFileSync(join(directory, name), bytes, { flag: 'wx', mode: 0o600 });
    files[name] = { bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') };
  }
  writeFileSync(join(directory, 'manifest.json'), JSON.stringify({ format: 'evidect-credential-offline-demo-manifest/1',
    node: process.version, openssl: process.versions.openssl, files,
    notice: 'Unsigned reproduction inventory, not independent evidence or a source of trusted keys.' }, null, 2) + '\n',
  { flag: 'wx', mode: 0o600 });
  return generated.summary;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    if (process.argv.length !== 3) throw new Error('USAGE');
    process.stdout.write(JSON.stringify(writeOfflineDemo(process.argv[2]), null, 2) + '\n');
  } catch {
    process.stderr.write('Synthetic offline export failed. Supply one new output directory; existing paths are not replaced.\n');
    process.exitCode = 1;
  }
}
