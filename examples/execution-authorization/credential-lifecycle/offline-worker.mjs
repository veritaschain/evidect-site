/** Fixed local worker. Original JSON bytes are decoded and checked here, never reserialized by Python. */
import { createHash } from 'node:crypto';
import { TextDecoder } from 'node:util';
import { parseBoundedJSON } from './strict-json.mjs';
import { verifyCredentialEvidence, EXPECTATION_FORMAT } from './offline.mjs';
import { identifier, record } from './protocol.mjs';

const INPUT_FORMAT = 'evidect-credential-offline-worker-input/1';
const OUTPUT_FORMAT = 'evidect-credential-offline-worker-output/1';
const MAX_FILE_BYTES = 1024 * 1024;
const MAX_WIRE_BYTES = 4 * 1024 * 1024 + 1024;
const MAX_OUTPUT_BYTES = 128 * 1024;
const FIELDS = ['format', 'evidence_base64', 'trust_base64', 'expectation_base64'];
const hash = raw => createHash('sha256').update(raw).digest('hex');
const fail = () => { throw new TypeError('INVALID_WORKER_INPUT'); };

function decode(value) {
  if (typeof value !== 'string' || value.length === 0 || value.length > 4 * Math.ceil(MAX_FILE_BYTES / 3) ||
      !/^[A-Za-z0-9+/]*={0,2}$/.test(value)) fail();
  const raw = Buffer.from(value, 'base64');
  if (raw.length === 0 || raw.length > MAX_FILE_BYTES || raw.toString('base64') !== value) fail();
  return raw;
}

function parseOriginal(raw) {
  try { return parseBoundedJSON(new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(raw)); }
  catch { return null; }
}

try {
  if (process.argv.length !== 2) fail();
  const chunks = []; let size = 0;
  for await (const chunk of process.stdin) {
    size += chunk.length; if (size > MAX_WIRE_BYTES) fail(); chunks.push(chunk);
  }
  const wire = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(Buffer.concat(chunks));
  // This transport is generated by the fixed Python adapter. Requiring its
  // compact encoding also rejects duplicate wire keys; original documents are
  // independently parsed below by the stricter, bounded evidence JSON reader.
  const input = JSON.parse(wire);
  record(input, FIELDS);
  if (input.format !== INPUT_FORMAT || JSON.stringify(Object.keys(input)) !== JSON.stringify(FIELDS) ||
      JSON.stringify(input) !== wire) fail();
  const evidenceRaw = decode(input.evidence_base64), trustRaw = decode(input.trust_base64),
    expectationRaw = decode(input.expectation_base64);
  const evidence = parseOriginal(evidenceRaw), trust = parseOriginal(trustRaw), expectation = parseOriginal(expectationRaw);
  let expectedContextId, expectedRequestDigests;
  try {
    record(expectation, ['format', 'contextId', 'requestDigests']);
    if (expectation.format !== EXPECTATION_FORMAT || !identifier(expectation.contextId)) fail();
    expectedContextId = expectation.contextId; expectedRequestDigests = expectation.requestDigests;
  } catch { /* Missing/invalid receiver configuration is not adopted from the evidence. */ }
  const result = verifyCredentialEvidence({ evidence, trust, expectedContextId, expectedRequestDigests });
  const output = { format: OUTPUT_FORMAT, evidence_sha256: hash(evidenceRaw), trust_sha256: hash(trustRaw),
    expectation_sha256: hash(expectationRaw), expected_context_id: expectedContextId ?? null, result };
  const encoded = JSON.stringify(output);
  if (Buffer.byteLength(encoded) + 1 > MAX_OUTPUT_BYTES) fail();
  process.stdout.write(encoded + '\n');
  process.exitCode = result.evidence_consistency === 'VALID' ? 0 : result.evidence_consistency === 'INVALID' ? 1 : 2;
} catch {
  process.stdout.write(JSON.stringify({ format: 'evidect-credential-offline-worker-error/1', reason: 'WORKER_INPUT_OR_OPERATION_INVALID' }) + '\n');
  process.exitCode = 2;
}
